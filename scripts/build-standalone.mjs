// Builds dist/route-plus-standalone.html — ONE file with every style, script
// and image inside it. Double-click it and it works: no server, no internet,
// no "raw HTML" look (the original problem: opening index.html on its own left
// its CSS, images and JavaScript modules behind).
//
// How: a tiny bundler follows the ES-module imports from web/js/main.js,
// wraps each module in its own function scope, and inlines the CSS files.
// Run:  npm run build

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const web = path.join(root, 'web');
const read = f => fs.readFileSync(f, 'utf8');

// ---------------------------------------------------------------- JS bundling
const modules = new Map(); // absolute path → { code, deps }
const order = [];

function parseImports(code) {
  const re = /import\s+([\s\S]*?)\s+from\s+['"](.+?)['"];?/g;
  const out = [];
  let m;
  while ((m = re.exec(code))) out.push({ full: m[0], clause: m[1].trim(), spec: m[2] });
  return out;
}

function visit(file) {
  if (modules.has(file)) return;
  const code = read(file);
  const imports = parseImports(code);
  modules.set(file, { code, imports });
  for (const imp of imports) visit(path.resolve(path.dirname(file), imp.spec));
  order.push(file);
}

function transform(file) {
  const { code, imports } = modules.get(file);
  let body = code;
  for (const imp of imports) {
    const target = JSON.stringify(path.relative(root, path.resolve(path.dirname(file), imp.spec)));
    let replacement;
    if (imp.clause.startsWith('* as ')) replacement = `const ${imp.clause.slice(5).trim()} = __m[${target}];`;
    else if (imp.clause.startsWith('{')) replacement = `const ${imp.clause.replace(/\s+as\s+/g, ': ')} = __m[${target}];`;
    else throw new Error(`Unsupported import in ${file}: ${imp.full}`);
    body = body.replace(imp.full, replacement);
  }
  const exported = new Set();
  body = body.replace(/export\s+(async\s+function|function|const|let|class)\s+([A-Za-z_$][\w$]*)/g, (_, kind, name) => { exported.add(name); return `${kind} ${name}`; });
  body = body.replace(/export\s*\{([^}]*)\};?/g, (_, names) => { names.split(',').map(n => n.trim()).filter(Boolean).forEach(n => exported.add(n)); return ''; });
  if (/\bexport\b\s/.test(body.replace(/\/\/.*$/gm, ''))) throw new Error(`Unhandled export form in ${file}`);
  const key = JSON.stringify(path.relative(root, file));
  return `// ---- ${path.relative(root, file)}\n__m[${key}] = await (async () => {\n${body}\nreturn { ${[...exported].join(', ')} };\n})();\n`;
}

visit(path.join(web, 'js', 'main.js'));
const bundle = `(async () => {\nconst __m = {};\n${order.map(transform).join('\n')}\n})().catch(e => { document.body.insertAdjacentHTML('afterbegin', '<p style="padding:16px;background:#f5dccd">ROUTE+ could not start: ' + e.message + '</p>'); console.error(e); });`;

// ---------------------------------------------------------------- HTML
let html = read(path.join(web, 'index.html'));
html = html.replace(/<link rel="stylesheet" href="([^"]+)">/g, (_, href) => `<style>\n${read(path.join(web, href))}\n</style>`);
html = html.replace(/\s*<link rel="manifest"[^>]*>/, '');
html = html.replace(/<script type="module" src="js\/main.js"><\/script>/, '');
html = html.replace('</body>', `<script>\n${bundle.replace(/<\/script/gi, '<\\/script')}\n</script>\n</body>`);
const hero = fs.readFileSync(path.join(web, 'assets/images/hero.jpg')).toString('base64');
html = html.replace('src="assets/images/hero.jpg"', `src="data:image/jpeg;base64,${hero}"`);
html = html.replace(/\s*<a class="button" href="companion.html" id="companion-link">[^<]*<\/a>/, '');
html = html.replace('<head>', '<head>\n  <!-- ROUTE+ standalone build: generated by scripts/build-standalone.mjs. Edit files in web/ and shared/, not this file. -->');

fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
const out = path.join(root, 'dist', 'route-plus-standalone.html');
fs.writeFileSync(out, html);
console.log(`Built ${path.relative(root, out)} — ${order.length} modules, ${(html.length / 1024).toFixed(0)} KB`);
